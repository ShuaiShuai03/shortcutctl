import Foundation

public struct RuntimeTest: Codable, Equatable, Sendable {
    public var name: String
    public var input: String?
    public var expectedOutput: String

    public init(name: String, input: String? = nil, expectedOutput: String) {
        self.name = name
        self.input = input
        self.expectedOutput = expectedOutput
    }

    private enum CodingKeys: String, CodingKey { case name, input, expectedOutput }

    public init(from decoder: any Decoder) throws {
        let keys = try decoder.container(keyedBy: AnyKey.self).allKeys.map(\.stringValue)
        guard Set(keys).subtracting(["name", "input", "expectedOutput"]).isEmpty else {
            throw ToolFailure(
                "unknown_test_field", "Runtime tests support only name, input, and expectedOutput fields.",
                "运行测试仅支持 name、input 和 expectedOutput 字段。", exitCode: 3)
        }
        let container = try decoder.container(keyedBy: CodingKeys.self)
        name = try container.decode(String.self, forKey: .name)
        input = try container.decodeIfPresent(String.self, forKey: .input)
        expectedOutput = try container.decode(String.self, forKey: .expectedOutput)
    }
}

public struct WorkflowProject: Codable, Equatable, Sendable {
    public var schemaVersion: Int
    public var name: String
    public var workflow: PlistValue
    public var tests: [RuntimeTest]

    public init(name: String, workflow: PlistValue, tests: [RuntimeTest] = []) {
        self.schemaVersion = 1
        self.name = name
        self.workflow = workflow
        self.tests = tests
    }

    private enum CodingKeys: String, CodingKey { case schemaVersion, name, workflow, tests }

    public init(from decoder: any Decoder) throws {
        let keys = try decoder.container(keyedBy: AnyKey.self).allKeys.map(\.stringValue)
        let unknown = Set(keys).subtracting(["schemaVersion", "name", "workflow", "tests"])
        guard unknown.isEmpty else {
            throw ToolFailure(
                "unknown_project_field",
                "Unknown project fields: \(unknown.sorted().joined(separator: ", ")). Put native metadata inside workflow.",
                "项目包含未知字段，请将原生元数据放入 workflow。", exitCode: 3)
        }
        let container = try decoder.container(keyedBy: CodingKeys.self)
        schemaVersion = try container.decode(Int.self, forKey: .schemaVersion)
        guard schemaVersion == 1 else {
            throw ToolFailure(
                "unsupported_schema", "Supported project schemaVersion is 1; received \(schemaVersion).",
                "仅支持项目 schemaVersion 1。", exitCode: 3)
        }
        name = try container.decode(String.self, forKey: .name)
        workflow = try container.decode(PlistValue.self, forKey: .workflow)
        tests = try container.decodeIfPresent([RuntimeTest].self, forKey: .tests) ?? []
    }
}

public enum WorkflowFormat: String, Sendable { case xml, binary }

public enum WorkflowCodec {
    public static func encodeProject(_ project: WorkflowProject) throws -> Data {
        let encoder = JSONEncoder()
        encoder.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]
        return try encoder.encode(project) + Data([10])
    }

    public static func decodeProject(_ data: Data) throws -> WorkflowProject {
        do {
            let project = try JSONDecoder().decode(WorkflowProject.self, from: data)
            _ = try project.workflow.propertyList()
            return project
        } catch let error as ToolFailure { throw error } catch {
            throw ToolFailure(
                "invalid_project", "Invalid project JSON: \(error.localizedDescription)", "项目 JSON 无效。",
                hint: "Use a schemaVersion 1 project generated by create or decompile.", exitCode: 3)
        }
    }

    public static func decodeWorkflow(_ data: Data, name: String) throws -> WorkflowProject {
        if data.starts(with: Data("AEA1".utf8)) {
            let payload = try SignedContainer.decode(data)
            return try decodeWorkflow(payload, name: name)
        }
        let payload = data.starts(with: [0xEF, 0xBB, 0xBF]) ? data.dropFirst(3) : data[...]
        let leading = payload.drop(while: { [9, 10, 13, 32].contains($0) }).first
        if leading == 123 { return try decodeProject(Data(payload)) }
        do {
            let raw = try PropertyListSerialization.propertyList(from: data, options: [], format: nil)
            let workflow = try PlistValue(propertyList: raw)
            guard workflow.dictionary != nil, workflow["WFWorkflowActions"]?.array != nil else {
                throw ToolFailure(
                    "invalid_workflow", "Expected a workflow dictionary containing WFWorkflowActions.",
                    "需要包含 WFWorkflowActions 的工作流字典。", exitCode: 3)
            }
            return WorkflowProject(name: workflow["WFWorkflowName"]?.string ?? name, workflow: workflow)
        } catch let error as ToolFailure { throw error } catch {
            throw ToolFailure(
                "unsupported_workflow",
                "Input is not a readable workflow plist, signed AEA1 container, or project JSON.",
                "输入不是可读取的工作流属性列表、已签名 AEA1 容器或项目 JSON。",
                hint: "Encrypted AEA profiles are unsupported; retain the unsigned source when building.",
                exitCode: 4)
        }
    }

    public static func load(_ path: URL) throws -> WorkflowProject {
        try decodeWorkflow(SafeFiles.read(path), name: path.deletingPathExtension().lastPathComponent)
    }
}

public enum WorkflowCompiler {
    public static func compile(_ project: WorkflowProject, format: WorkflowFormat) throws -> Data {
        let errors = WorkflowValidator.validate(project).filter { $0.severity == .error }
        guard errors.isEmpty else {
            throw ToolFailure(
                "validation_failed", "Workflow has \(errors.count) structural error(s): \(errors[0].message)",
                "工作流包含 \(errors.count) 个结构错误：\(errors[0].messageZH)", hint: "Run lint --json for every diagnostic.",
                exitCode: 3)
        }
        let value = try project.workflow.propertyList()
        do {
            let data =
                try format == .xml
                ? PropertyListSerialization.data(fromPropertyList: value, format: .xml, options: 0)
                : CanonicalBinaryPlist.encode(project.workflow)
            guard data.count <= SafeFiles.maximumBytes else {
                throw ToolFailure(
                    "file_too_large", "Compiled workflow exceeds the 16 MiB file limit.", "编译后的工作流超过 16 MiB 文件限制。",
                    exitCode: 5)
            }
            let restored = try PlistValue(
                propertyList: PropertyListSerialization.propertyList(from: data, options: [], format: nil))
            guard restored == project.workflow else {
                throw ToolFailure(
                    "lossy_serialization", "The selected property-list format would change workflow values.",
                    "所选属性列表格式会改变工作流中的值。",
                    hint: "Use --format binary for fractional dates or signed zero. No output was written.",
                    exitCode: 3)
            }
            return data
        } catch let error as ToolFailure {
            throw error
        } catch {
            throw ToolFailure(
                "compile_failed", "Cannot serialize workflow: \(error.localizedDescription)", "无法序列化工作流。", exitCode: 3)
        }
    }
}
